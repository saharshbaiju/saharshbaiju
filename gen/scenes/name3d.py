RAINBOW = ["red", "orange", "yellow", "green", "cyan", "blue", "magenta"]
DIMS = {"red": "dred", "orange": "dyellow", "yellow": "dyellow", "green": "dgreen",
        "cyan": "dcyan", "blue": "dblue", "magenta": "dmagenta"}


def render(text="SAHARSH", n=72, depth=3, W=None, H=16):
    text = text.upper()
    cols = len(text) * 6 - 1
    W = W or cols * 2 + 12
    vox = []                      # (x, y, z, letter_index, is_front)
    for li, ch in enumerate(text):
        bm = FONT.get(ch, FONT[" "])
        for r, row in enumerate(bm):
            for c, bit in enumerate(row):
                if bit == "1":
                    x = li * 6 + c - cols / 2 + 0.5
                    y = 3 - r
                    for d in range(depth):
                        vox.append((x, y, depth / 2 - 0.5 - d, li, d == 0))
    frames = []
    for f in range(n):
        a = 2 * math.pi * f / n
        ca, sa = math.cos(a), math.sin(a)
        wob = math.sin(a) * 0.18
        cw, sw = math.cos(wob), math.sin(wob)
        g = Grid(W, H)
        zbuf = {}
        for (x, y, z, li, front) in vox:
            # rotate about Y (spin) then about X (wobble)
            x1 = x * ca + z * sa
            z1 = -x * sa + z * ca
            y1 = y * cw - z1 * sw
            z2 = y * sw + z1 * cw
            per = 60.0 / (60.0 - z2 * 0.9)
            sx = int(round(W / 2 + x1 * 2 * per))
            sy = int(round(H / 2 - y1 * per))
            for key in ((sx, sy), (sx + 1, sy)):
                if key in zbuf and zbuf[key][0] >= z2: continue
                zbuf[key] = (z2, li, front)
        for (sx, sy), (z2, li, front) in zbuf.items():
            base = RAINBOW[li % len(RAINBOW)]
            # front faces bright when facing the viewer, extrusion dim
            facing = ca > 0
            if front and facing:
                g.put(sx, sy, "@", base)
            elif front:
                g.put(sx, sy, "#", DIMS[base])
            else:
                g.put(sx, sy, "#" if abs(sa) > 0.5 else "%", DIMS[base])
        frames.append(g)
    return frames
